/**
 * The reviewed allowlist of database objects the `anon` role can reach.
 *
 * WHAT THIS IS
 *   A committed record of exactly what the public anon key can touch in the
 *   `public` schema of the BingoBlast project, as reviewed by a human. Every
 *   entry below was read from the live catalogue, checked against what the app
 *   actually needs, and kept deliberately.
 *
 *   `tests/anon-access.test.ts` reads the live catalogue and fails when the
 *   database grants anon anything this file does not list, or grants more on a
 *   listed object than this file allows. The test skips with an explanation when
 *   no database connection is configured, so it is inert by default and only
 *   speaks when pointed at a real project.
 *
 * WHY IT EXISTS
 *   Anon reach in this project has drifted twice before, silently and on every
 *   build. On 30 July 2026 the four host RPCs were found anon-callable
 *   (`call_next_number`, `void_last_number`, `record_winner_atomic`,
 *   `assert_is_host`), repaired by 20260730070705, and then found to be
 *   recreated anon-callable on every fresh build until 5f4755d folded the revoke
 *   into the migration that creates them. Three migrations that production had
 *   applied were missing from this repository entirely and had to be recovered
 *   from `supabase_migrations.schema_migrations.statements`.
 *
 *   The cause is still armed. `pg_default_acl` on this project grants anon
 *   EXECUTE on every new function in `public`, and every table privilege on
 *   every new table, so the next `create function` picks anon straight back up
 *   with nobody having written a grant. `supabase/tests/convention-gap.test.sql`
 *   reproduces that in a container. No migration in this repository revokes
 *   those default privileges, so this allowlist is the detection that stands in
 *   for a fix that has not been made.
 *
 *   This app moves money: snowball jackpots, prize amounts and tie shares. Anon
 *   reach is not a theoretical concern here.
 *
 * WHAT MUST NEVER APPEAR IN THIS FILE
 *   No money-moving function and no host-only or admin-only function may ever be
 *   added to `ANON_ALLOWLIST`. Those are listed by name in `NEVER_ALLOWLIST`
 *   below and the test enforces it, so a careless edit to this file fails rather
 *   than passing quietly. They are reachable only by an authenticated host or
 *   admin, through `assert_is_host()` or `assert_is_admin()`, and a grant to
 *   anon on any of them is an incident, not a configuration choice. If one of
 *   them shows up in the live catalogue, the fix is a migration that revokes it,
 *   never an edit to this file.
 *
 * HOW TO UPDATE IT, DELIBERATELY
 *   1. Do not edit this file to make a failing test pass. A failure means the
 *      live database changed. Find out which migration changed it first.
 *   2. If the new reach is wanted, add the entry with a `why` that says which
 *      feature needs it and which migration granted it, in the same pull request
 *      as that migration.
 *   3. If the new reach is not wanted, write a migration that revokes it. The
 *      shape that actually closes it is both revokes together, because
 *      `create function` grants PUBLIC its own EXECUTE and anon is a member of
 *      PUBLIC: `revoke execute on function ... from public, anon;`
 *   4. Re-run `npx tsx --test tests/anon-access.test.ts` with `SUPABASE_DB_URL`
 *      set, and paste the result into the pull request.
 *
 * A NOTE ON THE TABLE ENTRIES
 *   Anon holds every table privilege on every table in `public`. That is not a
 *   decision anyone here made: it is what Supabase's default privileges grant,
 *   and removing it project-wide is a change with real blast radius. RLS is
 *   therefore the control, and every table below carries RLS with policies. The
 *   `why` on each entry records what RLS actually lets anon do, checked against
 *   the live REST API with the public anon key on 4 September 2026, not inferred
 *   from the policy text. The value of listing them is that a NEW table appears
 *   here as a failure the day it is created, while it is still empty.
 *
 * EVIDENCE
 *   Read from project bcmorqsgeumtmhvctvgu (BingoBlast) on 4 September 2026,
 *   read-only. Nothing was granted, revoked or migrated to produce it.
 */

export type AnonObjectKind =
  | 'table'
  | 'view'
  | 'materialized view'
  | 'sequence'
  | 'function';

/** One object the live catalogue says anon can reach. */
export interface AnonCatalogueEntry {
  kind: AnonObjectKind;
  /** Tables, views and sequences use the bare relation name. Functions use
   *  `name(identity arguments)`, so an overload cannot hide behind its sibling. */
  name: string;
  privileges: string[];
}

export interface AnonAllowlistEntry extends AnonCatalogueEntry {
  why: string;
}

