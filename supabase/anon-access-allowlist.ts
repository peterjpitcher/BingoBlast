/**
 * The catalogue query the test runs against the live database. Read-only.
 *
 * It asks `has_*_privilege` rather than reading ACL arrays, because that is the
 * question worth answering: what anon can actually do, including anything it
 * inherits through PUBLIC. Functions are keyed by identity arguments so an
 * overload cannot hide behind a sibling with the same name, which is the exact
 * shape the July 2026 drift took.
 */
export const ANON_CATALOGUE_QUERY = `
with table_privs as (
  select case when current_setting('server_version_num')::int >= 170000
              then array[${TABLE_PRIVILEGES_PG17.map((p) => `'${p}'`).join(',')}]
              else array[${TABLE_PRIVILEGES.map((p) => `'${p}'`).join(',')}] end as names
),
rel as (
  select case c.relkind when 'r' then 'table' when 'p' then 'table'
                        when 'v' then 'view' when 'm' then 'materialized view' end as kind,
         c.relname as name,
         (select coalesce(array_agg(p order by p), array[]::text[])
            from table_privs, unnest(table_privs.names) p
           where has_table_privilege('anon', c.oid, p)) as privileges
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r','p','v','m')
),
seq as (
  select 'sequence' as kind, c.relname as name,
         (select coalesce(array_agg(p order by p), array[]::text[])
            from unnest(array[${SEQUENCE_PRIVILEGES.map((p) => `'${p}'`).join(',')}]) p
           where has_sequence_privilege('anon', c.oid, p)) as privileges
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'S'
),
fn as (
  select 'function' as kind,
         p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as name,
         array['EXECUTE'] as privileges
    from pg_proc p
   where p.pronamespace = 'public'::regnamespace
     and has_function_privilege('anon', p.oid, 'EXECUTE')
)
select coalesce(json_agg(row_to_json(x) order by x.kind, x.name), '[]'::json) as reachable
  from (
    select * from rel where cardinality(privileges) > 0
    union all select * from seq where cardinality(privileges) > 0
    union all select * from fn
  ) x;
`.trim();

/** One way the live database is wider than the allowlist. */
export interface AnonAccessFinding {
  kind: AnonObjectKind;
  name: string;
  /** `unlisted` is an object anon can reach that the allowlist does not mention.
   *  `widened` is a listed object holding privileges beyond those allowed. */
  problem: 'unlisted' | 'widened';
  extraPrivileges: string[];
  /** Set when this object is a reviewed, still-open item rather than new drift. */
  knownOpenItem?: string;
}

export interface AnonAccessDiff {
  findings: AnonAccessFinding[];
  /** Allowlisted objects the live database no longer grants, or grants less of.
   *  Not a failure: the world got tighter. Reported so the file can be trimmed. */
  stale: string[];
}

const keyOf = (kind: string, name: string): string => `${kind} ${name}`;

/**
 * Compare a live catalogue reading against the allowlist. Pure, so the rules are
 * unit-tested without a database.
 */
export function diffAnonAccess(
  reachable: readonly AnonCatalogueEntry[],
  allowlist: readonly AnonAllowlistEntry[] = ANON_ALLOWLIST,
  openItems: readonly AnonOpenItem[] = ANON_OPEN_ITEMS,
): AnonAccessDiff {
  const allowed = new Map<string, AnonAllowlistEntry>(
    allowlist.map((entry) => [keyOf(entry.kind, entry.name), entry]),
  );
  const open = new Map<string, AnonOpenItem>(
    openItems.map((item) => [keyOf(item.kind, item.name), item]),
  );

  const findings: AnonAccessFinding[] = [];
  const seen = new Set<string>();

  for (const entry of reachable) {
    const key = keyOf(entry.kind, entry.name);
    seen.add(key);
    const allowedEntry = allowed.get(key);

    if (!allowedEntry) {
      findings.push({
        kind: entry.kind,
        name: entry.name,
        problem: 'unlisted',
        extraPrivileges: [...entry.privileges].sort(),
        ...(open.has(key) ? { knownOpenItem: open.get(key)!.why } : {}),
      });
      continue;
    }

    const permitted = new Set(allowedEntry.privileges);
    const extra = entry.privileges.filter((p) => !permitted.has(p)).sort();
    if (extra.length > 0) {
      findings.push({
        kind: entry.kind,
        name: entry.name,
        problem: 'widened',
        extraPrivileges: extra,
      });
    }
  }

  const stale = [...allowed.keys()].filter((key) => !seen.has(key)).sort();

  return { findings, stale };
}

/** A failure message that names the objects and says what to do about them. */
export function describeAnonAccessFindings(
  findings: readonly AnonAccessFinding[],
): string {
  const lines = [
    `anon can reach ${findings.length} object(s) that supabase/anon-access-allowlist.ts does not allow.`,
    '',
  ];

  for (const finding of findings) {
    if (finding.problem === 'unlisted') {
      lines.push(
        `  NOT ALLOWLISTED  ${finding.kind} ${finding.name}`,
        `                   anon holds: ${finding.extraPrivileges.join(', ')}`,
      );
      if (finding.knownOpenItem) {
        lines.push(
          '                   This is a reviewed, still-open item, not new drift:',
          `                   ${finding.knownOpenItem}`,
        );
      }
    } else {
      lines.push(
        `  WIDENED          ${finding.kind} ${finding.name}`,
        `                   anon gained: ${finding.extraPrivileges.join(', ')}`,
      );
    }
    lines.push('');
  }

  lines.push(
    'Do not edit the allowlist to make this pass. Find the migration that changed',
    'the database. If the reach is wanted, add it to the allowlist with a reason in',
    'the same pull request. If it is not, write a migration that revokes it, from',
    'PUBLIC and anon together, because create function grants PUBLIC its own EXECUTE',
    'and anon is a member of PUBLIC.',
  );

  return lines.join('\n');
}
